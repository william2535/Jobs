// Optional real Jobs + real Zone Sketch receiver integration. No reference files are edited.
import assert from 'node:assert/strict';
import {readFile,mkdtemp,rm} from 'node:fs/promises';
import {existsSync} from 'node:fs';
import {createServer} from 'node:http';
import {tmpdir} from 'node:os';
import {resolve,join,extname} from 'node:path';
import {execFileSync} from 'node:child_process';
import {chromium} from '@playwright/test';
import {validateJobPackage} from '../src/packages.js';
const reference=process.env.ZONE_SKETCH_REFERENCE;
if(!reference)throw Error('Set ZONE_SKETCH_REFERENCE to the external original index.html.');
const temporary=await mkdtemp(join(tmpdir(),'jobs-connected-source-'));
const runtime=join(temporary,'zone'),dist=join(temporary,'jobs');
const fixture=resolve('public/demo.zonesketch.json');
const serverFor=root=>createServer(async(req,res)=>{
 const path=new URL(req.url,'http://localhost').pathname;
 const file=resolve(root,'.'+(path.endsWith('/')?path+'index.html':path));
 if(!file.startsWith(root+'/'))return res.writeHead(403).end();
 try{const body=await readFile(file);res.writeHead(200,{'Content-Type':({'.html':'text/html','.js':'application/javascript','.json':'application/json','.css':'text/css','.svg':'image/svg+xml','.png':'image/png','.webp':'image/webp','.webmanifest':'application/manifest+json'})[extname(file)]||'application/octet-stream'}).end(body);}catch{res.writeHead(404).end();}
});
const listen=server=>new Promise(resolve=>server.listen(0,'127.0.0.1',resolve));
const jobsServer=serverFor(dist),zoneServer=serverFor(runtime);
await Promise.all([listen(jobsServer),listen(zoneServer)]);
const jobsOrigin=`http://127.0.0.1:${jobsServer.address().port}`,zoneOrigin=`http://127.0.0.1:${zoneServer.address().port}`;
execFileSync(process.execPath,[resolve('integrations/zone-sketch/install-bridge.mjs'),'--source',resolve(reference,'..'),'--output',runtime,'--jobs-origin',jobsOrigin],{stdio:'pipe'});
execFileSync(process.execPath,[resolve('node_modules/vite/bin/vite.js'),'build','--outDir',dist],{env:{...process.env,VITE_ZONE_SKETCH_URL:zoneOrigin+'/index.html'},stdio:'pipe'});
const browser=await chromium.launch({executablePath:process.env.PLAYWRIGHT_CHROMIUM_EXECUTABLE||(existsSync('/usr/bin/chromium')?'/usr/bin/chromium':undefined),args:['--no-sandbox']});
async function exportJob(page){const event=page.waitForEvent('download');await page.locator('.job-toolbar').getByRole('button',{name:'Export job',exact:true}).click();const download=await event;return validateJobPackage(await readFile(await download.path(),'utf8'));}
try{
 const context=await browser.newContext({viewport:{width:390,height:844}});
 const page=await context.newPage();
 await page.goto(jobsOrigin);
 await page.locator('#zone-file').setInputFiles(fixture);
 await page.getByRole('button',{name:'Save site',exact:true}).click();
 // Site-only launches carry null job identifiers and do not create a visit.
 const sitePopup=page.waitForEvent('popup');
 await page.getByRole('button',{name:'Edit site',exact:true}).click();
 const siteZone=await sitePopup;
 await siteZone.setViewportSize({width:1280,height:900});
 await siteZone.getByRole('button',{name:'Save to Jobs',exact:true}).waitFor();
 await siteZone.waitForFunction(()=>!document.querySelector('#jobsBridgeBar button').disabled);
 await siteZone.locator('#topCollapseBtn').click();
 await siteZone.locator('#projectMenuBtn').click();
 await siteZone.locator('#drawingDetails').click();
 await siteZone.locator('#revision').fill('SITE-BRIDGE');
 await siteZone.locator('#detailsSave').click();
 await siteZone.getByRole('button',{name:'Save to Jobs',exact:true}).click();
 await siteZone.waitForFunction(()=>document.getElementById('jobsBridgeBar').textContent.includes('Saved in Jobs.'));
 await siteZone.getByRole('button',{name:'Back to Jobs',exact:true}).click();
 await page.locator('[data-action="create"]').last().click();
 await page.getByRole('textbox',{name:'Assigned engineer',exact:true}).fill('Synthetic Bridge Engineer');
 await page.getByRole('button',{name:'Create job',exact:true}).last().click();
 await page.getByRole('button',{name:'Plan',exact:true}).click();
 await page.getByRole('button',{name:'MCP-01',exact:true}).click();
 await page.getByRole('combobox',{name:'Result',exact:true}).selectOption('Unsatisfactory');
 await page.getByRole('textbox',{name:'Observations',exact:true}).fill('Synthetic observation retained across actual engine edit.');
 await page.getByRole('button',{name:'Save device result',exact:true}).click();
 const before=await exportJob(page);
 await page.getByRole('button',{name:'Plan',exact:true}).click();
 const popup=page.waitForEvent('popup');
 await page.getByRole('button',{name:'Edit site',exact:true}).click();
 const zone=await popup;
 await zone.setViewportSize({width:1280,height:900});
 await zone.waitForFunction(()=>!document.querySelector('#jobsBridgeBar button')?.disabled);
 await zone.locator('#topCollapseBtn').click();
 await zone.locator('#projectMenuBtn').click();
 await zone.locator('#drawingDetails').click();
 await zone.locator('#revision').fill('JOB-BRIDGE');
 await zone.locator('#detailsSave').click();
 await zone.getByRole('button',{name:'Save to Jobs',exact:true}).click();
 await zone.waitForFunction(()=>document.getElementById('jobsBridgeBar').textContent.includes('Saved in Jobs.'));
 const after=await exportJob(page);
 assert.equal(after.job.id,before.job.id);
 assert.equal(after.site.id,before.site.id);
 assert.deepEqual(after.job.results,before.job.results);
 assert.ok(after.site.drawings.length>before.site.drawings.length);
 const current=after.site.drawings.find(d=>d.id===after.job.drawingId);
 assert.equal(current.revision,'JOB-BRIDGE');
 assert.ok(current.planPreviews.length>=2);
 assert.ok(current.planPreviews.some(p=>p.renderer==='ZoneSketch'&&p.overlayMode==='none'));
 assert.deepEqual(current.assets.map(a=>a.id),before.site.drawings.find(d=>d.id===before.job.drawingId).assets.map(a=>a.id));
 await page.getByTestId('plan-png').waitFor();
 const png=await page.getByTestId('plan-png').getAttribute('src');
 assert.ok(current.planPreviews.some(p=>p.image===png&&p.renderer==='ZoneSketch'));
 assert.ok(await page.evaluate(()=>document.documentElement.scrollWidth<=window.innerWidth+1));
 await page.evaluate(async()=>navigator.serviceWorker.ready);
 await page.waitForFunction(()=>!!navigator.serviceWorker.controller);
 await context.setOffline(true);
 await page.reload();
 await page.getByTestId('job-card').click();
 await page.getByRole('button',{name:'Plan',exact:true}).click();
 await page.waitForFunction(()=>{const image=document.querySelector('[data-testid="plan-png"]');return image?.complete&&image.naturalWidth>0;});
 assert.equal(await page.getByTestId('plan-png').getAttribute('src'),png);
 const offline=await exportJob(page);
 assert.deepEqual(offline.site.drawings,after.site.drawings);
 assert.deepEqual(offline.job.results,after.job.results);
 console.log(JSON.stringify({actualJobsProductionBuild:true,actualZoneEngine:true,automaticSiteLoad:true,automaticJobLoad:true,siteAndJobSaveAck:true,enginePNGs:true,stableSiteJobAssetIds:true,resultsRetained:true,previousRevisionsRetained:true,offlinePNGReloadAndExport:true,mobileWidth390:true}));
}finally{await browser.close();await Promise.all([new Promise(resolve=>jobsServer.close(resolve)),new Promise(resolve=>zoneServer.close(resolve))]);await rm(temporary,{recursive:true,force:true});}
